/** Inline SVG icons — single consistent stroke style (no external deps). */

import type { ReactNode } from "react";

type IconProps = { className?: string; size?: number };

const defaults = { size: 18, className: "icon" };

function Svg({
  children,
  className = defaults.className,
  size = defaults.size,
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
    >
      {children}
    </svg>
  );
}

